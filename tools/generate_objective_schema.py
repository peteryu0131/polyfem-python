"""Extract objective rules verbatim from PolyFEM's JSE spec for packaged Python use.

This is a data snapshot, not a second class generator. The existing class
generator does not type the recursively nested objective objects. Runtime code
uses these rules to preserve those payloads without hand-maintained type lists.
Run with --check to detect drift without editing generated data.
"""
import argparse
import json
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "polyfem/json-specs/objective-spec.json"
OUTPUT = ROOT / "polyfempy/differentiable_api/_objective_schema_data.py"


def render():
    rows = json.loads(SOURCE.read_text(encoding="utf-8"))
    names = next(row["options"] for row in rows if row["pointer"] == "/type")
    objectives = {row["type_name"]: row for row in rows
                  if row["pointer"] == "/" and "type_name" in row}
    if set(names) != set(objectives):
        raise ValueError("Objective names and object definitions differ in source schema")
    fields = {}
    for row in rows:
        if row["pointer"] != "/":
            fields.setdefault(row["pointer"], []).append(row)
    return ('# Generated by tools/generate_objective_schema.py; do not edit.\n'
            '# Source: polyfem/json-specs/objective-spec.json\n\n'
            + 'OBJECTIVES = ' + pformat(objectives, sort_dicts=False) + '\n\n'
            + 'FIELDS = ' + pformat(fields, sort_dicts=False) + '\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("Objective schema snapshot is stale; run this tool without --check")
        print("Objective schema snapshot matches PolyFEM")
    else:
        OUTPUT.write_text(source, encoding="utf-8")
